import { ROUTE_TABLE } from './routes';
import { RouteDefinition } from './types';

export function generateOpenApiSpec(host: string = '127.0.0.1:3001') {
  const paths: Record<string, any> = {};

  for (const route of ROUTE_TABLE) {
    // Convert :param to {param} for OpenAPI path specification
    const openApiPath = route.path.replace(/:([a-zA-Z0-9_]+)/g, '{$1}');
    if (!paths[openApiPath]) {
      paths[openApiPath] = {};
    }

    const method = route.method.toLowerCase();
    const pathParams = (route.path.match(/:([a-zA-Z0-9_]+)/g) || []).map((p) => ({
      name: p.slice(1),
      in: 'path',
      required: true,
      schema: { type: 'string' },
    }));

    const tags = [getCategoryForPath(route.path)];

    paths[openApiPath][method] = {
      summary: route.summary || `${route.method} ${route.path}`,
      description: `Access: ${route.auth === 'public' ? 'Public' : `Requires role: ${route.minRole || 'READ_ONLY'}`}${route.audit ? ' (Audited)' : ''}`,
      tags,
      parameters: pathParams.length > 0 ? pathParams : undefined,
      security: route.auth === 'public' ? [] : [{ BearerAuth: [] }, { ApiKeyAuth: [] }],
      responses: {
        '200': {
          description: 'Successful response',
        },
        ...(route.auth !== 'public'
          ? {
              '401': { description: 'Unauthorized - Missing or invalid Bearer JWT or x-api-key' },
              '403': { description: 'Forbidden - Insufficient role privilege' },
            }
          : {}),
      },
    };
  }

  return {
    openapi: '3.0.3',
    info: {
      title: 'Ownbase Native Windows Server REST API',
      version: '1.0.0',
      description: 'Authoritative, contract-driven REST API for Ownbase Native Windows Server Platform. Complete RBAC, process supervisor, reverse proxy, storage, and database management.',
      contact: {
        name: 'Ownbase Platform Team',
      },
    },
    servers: [
      {
        url: `http://${host}`,
        description: 'Direct Hub Server Gateway',
      },
      {
        url: 'http://localhost',
        description: 'Caddy Edge Ingress (Port 80)',
      },
    ],
    components: {
      securitySchemes: {
        BearerAuth: {
          type: 'http',
          scheme: 'bearer',
          bearerFormat: 'JWT',
          description: '15-minute access JWT token passed in Authorization: Bearer <token>',
        },
        ApiKeyAuth: {
          type: 'apiKey',
          in: 'header',
          name: 'x-api-key',
          description: '32-byte permanent or scoped API key generated by root administrator',
        },
      },
    },
    paths,
  };
}

export function getEndpointCatalog(): Array<{
  id: string;
  method: string;
  path: string;
  category: string;
  summary: string;
  auth: string;
  minRole?: string;
}> {
  return ROUTE_TABLE.map((r) => ({
    id: `${r.method.toLowerCase()}-${r.path.replace(/[\/:]/g, '-')}`,
    method: r.method,
    path: r.path,
    category: getCategoryForPath(r.path),
    summary: r.summary || `${r.method} ${r.path}`,
    auth: r.auth,
    minRole: r.minRole,
  }));
}

function getCategoryForPath(path: string): string {
  if (path.includes('/auth') || path.includes('/setup')) return 'Authentication & Identity';
  if (path.includes('/system') || path.includes('/postgres') || path.includes('/migration') || path.includes('/bootstrap') || path.includes('/ping')) return 'System & Database Telemetry';
  if (path.includes('/services') || path.includes('/process')) return 'Process Supervisor';
  if (path.includes('/routes') || path.includes('/caddy')) return 'Edge Gateway & Routing';
  if (path.includes('/tailscale')) return 'Tailscale Mesh';
  if (path.includes('/lifecycle')) return 'Lifecycle & Power';
  if (path.includes('/files')) return 'File Storage & Streaming';
  if (path.includes('/photos')) return 'Photos & Media';
  if (path.includes('/db/')) return 'Database Table Browser';
  if (path.includes('/audit')) return 'Security Audit';
  if (path.includes('/users') || path.includes('/api-keys')) return 'Administration';
  return 'General';
}
